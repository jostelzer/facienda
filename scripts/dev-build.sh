#!/bin/bash
# Build Facienda without an Apple developer account: scripts/dev-build.sh [--test] [--open]
#   --test  also runs the tests and the helper smoke checks
#   --open  then opens the build on sample data, so your own library stays untouched
# The Debug app is signed ad hoc and named Facienda Development, so macOS keeps it apart from an installed Facienda.
set -euo pipefail
cd "$(dirname "$0")/.."
run_tests=""
open_app=""
while test $# -gt 0; do
    case "$1" in
        --test) run_tests=1; shift ;;
        --open) open_app=1; shift ;;
        *) echo "Usage: scripts/dev-build.sh [--test] [--open]" >&2; exit 2 ;;
    esac
done
if ! command -v xcodegen >/dev/null; then echo "The Xcode project is generated by XcodeGen: brew install xcodegen" >&2; exit 1; fi
xcodegen generate --quiet
xcode=(xcodebuild -project Facienda.xcodeproj -scheme Facienda -configuration Debug -derivedDataPath build -destination "platform=macOS,arch=$(uname -m)" -quiet)
"${xcode[@]}" build
app="build/Build/Products/Debug/Facienda.app"
if test -n "$run_tests"; then
    # The app's tests live in the Xcode project; the package's own (core, bridge, companion) run under swift test.
    "${xcode[@]}" -only-testing:FaciendaAppTests test
    # Package.resolved also pins the app's packages, which swift test would otherwise drop from it.
    swift test --disable-automatic-resolution --quiet
    python3 scripts/test_release.py
    # Both run the bundled helpers against a throwaway library, never yours.
    python3 scripts/integration_smoke.py --helpers "$app/Contents/Helpers" --workspace
    python3 scripts/claude_smoke.py --helpers "$app/Contents/Helpers"
fi
echo "Built $app"
if test -n "$open_app"; then open -n "$app" --args --demo; fi
